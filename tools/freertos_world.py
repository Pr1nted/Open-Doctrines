#!/usr/bin/env python3
"""Turn templeos/world.odw into C that a microcontroller keeps in flash.

    tools/freertos_world.py templeos/world.odw build/od_world_data.c

The FreeRTOS edition plays the world the TempleOS edition plays, so it reads
the same baked file rather than baking its own from the .odmap: there is one
world for the two small builds, and tools/templeos_world.py is the only thing
that decides what is in it.

What is left out is everything a serial console cannot show: the raster, the
centres, the colours and the sea grid. What stays is what the rules read --
every province's owner, people, garrison, income, fort, area, industry,
resources, harbour and NEIGHBOURS, every country's code, name and treasury,
and every hull -- about 90 KB of const data, which the linker puts in flash.
The game copies only the numbers that change into RAM (freertos/core/od_world.c).
"""
from __future__ import annotations

import argparse
import struct
import sys

MAGIC, VERSION = b"ODTW", 8
HDR, PREC, CREC, SREC = 30, 50, 34, 6


def cstr(b: bytes) -> str:
    s = b.split(b"\0")[0].decode("latin-1")
    out = []
    for ch in s:
        o = ord(ch)
        if ch in '"\\':
            out.append("\\" + ch)
        elif 32 <= o < 127:
            out.append(ch)
        else:
            out.append("\\%03o" % o)
    return '"' + "".join(out) + '"'


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("odw")
    ap.add_argument("out")
    a = ap.parse_args()

    b = open(a.odw, "rb").read()
    if b[:4] != MAGIC:
        print(f"{a.odw} is not a world file", file=sys.stderr)
        return 1
    ver, w, h, np_, nc, runs, nadj, ns = struct.unpack_from("<HHHHHIIH", b, 4)
    if ver != VERSION:
        print(f"{a.odw} is version {ver}, this reads {VERSION}: re-bake it", file=sys.stderr)
        return 1

    off = HDR + runs
    provs = []
    for _ in range(np_):
        (pid, _cx, _cy, own, pop, army, inc, adjn, fort, adjo, area,
         ind, res, port, _pad) = struct.unpack_from("<IHHHIIHBBIIBBBB", b, off)
        name = b[off + 34:off + 49]
        provs.append((pid, own, pop, army, inc, adjn, fort, adjo, area, ind, res, port, name))
        off += PREC
    adj = list(struct.unpack_from(f"<{nadj}H", b, off))
    off += 2 * nadj
    ctrys = []
    for _ in range(nc):
        cid = struct.unpack_from("<H", b, off)[0]
        iso = b[off + 4:off + 7]
        tre = struct.unpack_from("<H", b, off + 8)[0]
        name = b[off + 14:off + 33]
        ctrys.append((cid, iso, tre, name))
        off += CREC
    ships = []
    for _ in range(ns):
        ships.append(struct.unpack_from("<HBBH", b, off))
        off += SREC

    for p in provs:
        if p[7] + p[5] > nadj:
            print("a province's neighbours run past the adjacency list", file=sys.stderr)
            return 1

    o = []
    o.append("/* GENERATED by tools/freertos_world.py from templeos/world.odw -- do not edit. */")
    o.append('#include "od_world.h"')
    o.append("")
    o.append(f"const uint16_t od_np = {np_};")
    o.append(f"const uint16_t od_nc = {nc};")
    o.append(f"const uint16_t od_ns = {ns};")
    o.append("")
    o.append(f"const od_prov_t od_prov0[{max(np_, 1)}] = {{")
    for (pid, own, pop, army, inc, adjn, fort, adjo, area, ind, res, port, name) in provs:
        o.append(f"  {{{pid}u, {area}u, {pop}u, {army}u, {adjo}u, {own}, {inc}, "
                 f"{adjn}, {fort}, {ind}, {res}, {port}, {cstr(name)}}},")
    o.append("};")
    o.append("")
    o.append(f"const uint16_t od_adj[{max(nadj, 1)}] = {{")
    for i in range(0, nadj, 16):
        o.append("  " + ", ".join(str(x) for x in adj[i:i + 16]) + ",")
    o.append("};")
    o.append("")
    o.append(f"const od_ctry_t od_ctry0[{max(nc, 1)}] = {{")
    for (cid, iso, tre, name) in ctrys:
        o.append(f"  {{{cid}, {tre}, {cstr(iso)}, {cstr(name)}}},")
    o.append("};")
    o.append("")
    o.append(f"const od_ship_t od_ship0[{max(ns, 1)}] = {{")
    for (cid, kind, hp, prov) in ships:
        o.append(f"  {{{cid}, {prov}, {kind}, {hp}}},")
    o.append("};")
    with open(a.out, "w") as f:
        f.write("\n".join(o) + "\n")
    print(f"wrote {a.out}: {np_} provinces, {nadj} borders, {nc} countries, {ns} hulls")
    return 0


if __name__ == "__main__":
    sys.exit(main())
