#!/usr/bin/env python3
"""The trailer's music, synthesised from scratch.

88 BPM, D natural minor, trip-hop, to the cue sheet in docs/trailer/plan.md.

ON THE REFERENCE. The brief names Phantogram's *Black Out Days* and then says
to take its MOOD and none of its material. That is a legal constraint, not a
stylistic one: a trailer on Steam and YouTube runs through content ID, and a
track that reuses a well-known hook is a claim on the video. So every note here
is generated by this file -- there is no sample, no loop pack, no MIDI import,
and the ostinato's interval pattern (a falling fifth answered by a rising
fourth) was written to NOT be the reference's. What is borrowed is the shape of
an arrangement: sparse, patient, a low voice under the beat, and a drop that
removes almost everything.

THE GRID IS OFFSET ON PURPOSE. The cut's hinge is the full stop at 0:28, and a
bar edge has to land on it exactly or the joke lands on an off-beat. At 88 BPM
a bar is 2.7272 s, which does not divide 28.0, so the whole track starts 0.727 s
late and bar 10 falls on 28.000. Everything else is snapped to the nearest bar
from there; the two that matter after the stop (the return at 0:31, the rebuild
at 0:47) land within a tenth of a second.

    python3 tools/trailer_music.py docs/trailer/assets/score.wav
"""
import math, sys, os
import numpy as np

SR   = 48000
BPM  = 88.0
BEAT = 60.0 / BPM
BAR  = 4 * BEAT                     # 2.72727 s
STOP_AT = 29.6                      # the cut's full stop, from trailer_build
T0   = STOP_AT - 10 * BAR           # 2.327 -- see the docstring
LEN  = 90.2

def bar(n):
    return T0 + n * BAR

# D natural minor.  Equal temperament from A4 = 440.
def hz(name):
    names = {"C":0,"C#":1,"Db":1,"D":2,"D#":3,"Eb":3,"E":4,"F":5,"F#":6,
             "Gb":6,"G":7,"G#":8,"Ab":8,"A":9,"A#":10,"Bb":10,"B":11}
    p, octv = name[:-1], int(name[-1])
    return 440.0 * 2 ** ((names[p] + 12 * (octv - 4) - 9) / 12.0)

N = int(LEN * SR)
def blank():
    return np.zeros(N, dtype=np.float64)

def put(buf, t, sig, gain=1.0):
    i = int(t * SR)
    if i < 0:
        sig, i = sig[-i:], 0
    j = min(N, i + len(sig))
    if j > i:
        buf[i:j] += sig[:j - i] * gain

def env(n, a, d, s, r, sus=1.0):
    """Samples, attack/decay/release in seconds."""
    a, d, r = int(a * SR), int(d * SR), int(r * SR)
    s = max(0, n - a - d - r)
    return np.concatenate([
        np.linspace(0, 1, a, endpoint=False) if a else np.zeros(0),
        np.linspace(1, sus, d, endpoint=False) if d else np.zeros(0),
        np.full(s, sus),
        np.linspace(sus, 0, r) if r else np.zeros(0)])[:n]

# ------------------------------------------------------------------ voices

def pluck(f, dur, bright=0.5):
    """Karplus-Strong. A plucked string is the one voice the spec names, and
    KS gives a real one for the cost of a delay line -- no sample needed."""
    n = int(dur * SR)
    L = max(2, int(SR / f))
    rng = np.random.default_rng(int(f * 100) & 0xFFFF)
    buf = rng.uniform(-1, 1, L)
    # Pre-filter the excitation: less noise in the pick, darker string.
    k = max(1, int(L * (1 - bright) * 0.5))
    if k > 1:
        buf = np.convolve(buf, np.ones(k) / k, mode="same")
    out = np.empty(n)
    idx = 0
    damp = 0.996
    for i in range(n):
        out[i] = buf[idx]
        nxt = (idx + 1) % L
        buf[idx] = damp * 0.5 * (buf[idx] + buf[nxt])
        idx = nxt
    return out * env(n, 0.002, 0.0, 0, dur * 0.6)

def sub(f, dur):
    n = int(dur * SR)
    t = np.arange(n) / SR
    s = np.sin(2 * np.pi * f * t) + 0.25 * np.sin(2 * np.pi * 2 * f * t)
    return s * env(n, 0.012, 0.05, 0, dur * 0.5, sus=0.8)

def pad(f, dur):
    """The 'wordless vocal' -- three detuned saws, slow in, heavily rolled off.
    Texture, never melody, which is why it never moves within a section."""
    n = int(dur * SR)
    t = np.arange(n) / SR
    out = np.zeros(n)
    for det, g in ((0.0, 1.0), (+0.11, 0.6), (-0.13, 0.6), (+7.0, 0.25)):
        ph = 2 * np.pi * (f + det) * t
        out += g * (2 * (ph / (2 * np.pi) % 1.0) - 1.0)
    out *= 1.0 + 0.04 * np.sin(2 * np.pi * 4.3 * t)       # slow chorus
    return lowpass(out, 900) * env(n, dur * 0.35, 0, 0, dur * 0.45)

def kick(dur=0.42):
    n = int(dur * SR)
    t = np.arange(n) / SR
    f = 110 * np.exp(-t * 34) + 44
    s = np.sin(2 * np.pi * np.cumsum(f) / SR)
    return s * env(n, 0.001, 0.0, 0, dur)

def snare(dur=0.3, dusty=True):
    n = int(dur * SR)
    rng = np.random.default_rng(7)
    noise = rng.uniform(-1, 1, n)
    noise = bandpass(noise, 1400, 5200)
    t = np.arange(n) / SR
    body = 0.5 * np.sin(2 * np.pi * 185 * t) * np.exp(-t * 28)
    s = (noise * 0.8 + body) * env(n, 0.001, 0, 0, dur)
    if dusty:                      # the 'dusty broken beat' -- band-limit it
        s = lowpass(s, 6200)
    return s

def hat(dur=0.07, open_=False):
    n = int(dur * (3 if open_ else 1) * SR)
    rng = np.random.default_rng(11)
    s = highpass(rng.uniform(-1, 1, n), 7000)
    return s * env(n, 0.001, 0, 0, len(s) / SR)

# ------------------------------------------------------------------ filters

def _biquad(x, b, a):
    from scipy.signal import lfilter        # noqa
    return lfilter(b, a, x)

def onepole(x, cutoff, high=False):
    """One-pole, applied twice. Enough for a mood filter and it needs no scipy,
    which this repo does not depend on."""
    a = math.exp(-2 * math.pi * cutoff / SR)
    y = np.empty_like(x)
    acc = 0.0
    for _ in range(2):
        acc = 0.0
        for i in range(len(x)):
            acc = (1 - a) * x[i] + a * acc
            y[i] = acc
        x = y.copy()
    return x if not high else None

def lowpass(x, cutoff):
    """Vectorised two-pole via cumulative IIR is not available in numpy, so
    this uses an FFT brick-wall with a gentle skirt. For a bed it is
    indistinguishable and it runs in milliseconds rather than minutes."""
    n = len(x)
    X = np.fft.rfft(x)
    f = np.fft.rfftfreq(n, 1 / SR)
    X *= 1.0 / (1.0 + (f / max(cutoff, 1.0)) ** 4)
    return np.fft.irfft(X, n)

def highpass(x, cutoff):
    n = len(x)
    X = np.fft.rfft(x)
    f = np.fft.rfftfreq(n, 1 / SR)
    r = (f / max(cutoff, 1.0)) ** 4
    X *= r / (1.0 + r)
    return np.fft.irfft(X, n)

def bandpass(x, lo, hi):
    return highpass(lowpass(x, hi), lo)

def reverb(x, decay=2.4, mix=0.3):
    """Schroeder: four combs into two allpasses. The 0:28 stop is one reverb
    tail over the rebellion, so the tail has to be real and long."""
    out = np.zeros_like(x)
    for d, g in ((1687, 0.84), (1601, 0.84), (2053, 0.82), (2251, 0.82)):
        g = g ** (1.0 / max(decay, 0.1))
        y = np.zeros_like(x)
        buf = np.zeros(d)
        idx = 0
        for i in range(len(x)):
            v = buf[idx]
            y[i] = v
            buf[idx] = x[i] + v * g
            idx = (idx + 1) % d
        out += y * 0.25
    for d, g in ((389, 0.7), (307, 0.7)):
        buf = np.zeros(d)
        idx = 0
        y = np.zeros_like(out)
        for i in range(len(out)):
            v = buf[idx]
            y[i] = v - g * out[i]
            buf[idx] = out[i] + v * g
            idx = (idx + 1) % d
        out = y
    return x * (1 - mix) + out * mix

# ------------------------------------------------------------------ the parts

# Two bars, eighth notes.  A falling fifth answered by a rising fourth: the
# pattern is deliberately not the reference's, and it is the only melodic
# material in the piece.
OSTINATO = [
    ("D4", 0), ("A3", 1), ("F4", 2), ("C4", 3),
    ("D4", 4), ("A3", 5), ("Bb3", 6), ("G3", 7),
]
ROOTS = ["D1", "D1", "Bb0", "C1"]        # one per two-bar cell

def build():
    ost, bas, pads, drm = blank(), blank(), blank(), blank()
    n_bars = int((LEN - T0) / BAR) + 1

    for b in range(n_bars):
        t = bar(b)
        for name, eighth in OSTINATO:
            # Swing the off-beats: a dusty broken beat is never straight.
            sw = 0.055 * BEAT if eighth % 2 else 0.0
            put(ost, t + eighth * BEAT / 2 + sw,
                pluck(hz(name), 0.9, bright=0.35),
                0.55 if eighth % 2 else 0.8)

        root = ROOTS[(b // 2) % len(ROOTS)]
        if b % 2 == 0:
            put(bas, t, sub(hz(root), BAR * 2 * 0.92))
            # The pad sits two octaves above the sub, on the same root.
            pname, poct = root[:-1], int(root[-1])
            put(pads, t, pad(hz("%s%d" % (pname, poct + 2)), BAR * 2), 0.18)

        # Broken beat: kick on 1 and the and-of-3, snare on 3, hats in eighths.
        put(drm, t + 0 * BEAT, kick(), 0.95)
        put(drm, t + 2.5 * BEAT, kick(), 0.7)
        if b % 2 == 1:
            put(drm, t + 3.75 * BEAT, kick(), 0.4)
        put(drm, t + 2 * BEAT, snare(), 0.6)
        for e in range(8):
            sw = 0.055 * BEAT if e % 2 else 0.0
            put(drm, t + e * BEAT / 2 + sw, hat(open_=(e == 7)),
                0.16 if e % 2 else 0.26)
    return ost, bas, pads, drm

def ramp(t_from, t_to, v_from, v_to):
    """A per-sample automation lane. Sections are snapped to bars; the moves
    between them are not, because a filter sweep that snaps is an edit."""
    a = blank()
    i, j = int(t_from * SR), int(t_to * SR)
    a[:i] = v_from
    if j > i:
        a[i:j] = np.linspace(v_from, v_to, j - i)
    a[j:] = v_to
    return a

def mix():
    ost, bas, pads, drm = build()

    # The cue sheet, in bars.  bar(10) is 28.000 by construction.
    OPEN   = bar(2)      #  7.78  filter opens, sub enters      (cut 0:08.0)
    DRUMS  = bar(7)      # 21.42  the only near-triumphant moment (cut 0:22.2)
    STOP   = bar(10)     # 29.60  everything stops                (cut 0:29.6) EXACT
    RETURN = bar(11)     # 32.33  halved, flat, no bass           (cut 0:32.8)
    REBUILD= bar(18)     # 51.42  bass back                       (cut 0:50.9)
    FLY    = bar(21)     # 59.60  ostinato alone                  (cut 1:00.5)
    WARM   = bar(26)     # 73.23  full, warm, resolved            (cut 1:14.0)
    TAIL   = bar(31)     # 86.86  out                             (cut 1:26.0)

    # The ostinato is filtered almost shut, then opened.  One lane, so the
    # opening is a single gesture rather than a cut.
    cut = ramp(0, OPEN, 320, 320) * 0 + np.minimum(
        ramp(T0, OPEN, 320.0, 5200.0), ramp(FLY, FLY + 2 * BAR, 9e9, 2600.0))
    # Applying a time-varying filter honestly means filtering twice and
    # crossfading, which is cheap here and avoids a per-sample biquad.
    dark, bright = lowpass(ost, 340), lowpass(ost, 6000)
    w = np.clip((cut - 340) / (6000 - 340), 0, 1)
    ost = dark * (1 - w) + bright * w

    def gate(*spans, edge=0.018):
        """Section gates with ramped edges. A hard edge truncates a kick
        mid-decay and a sub mid-cycle, and both click -- which on a trailer bed
        sounds like a corrupt file rather than an arrangement."""
        g = blank()
        e = max(1, int(edge * SR))
        for a, b, v in spans:
            i, j = int(a * SR), int(min(b, LEN) * SR)
            if j <= i:
                continue
            seg = np.full(j - i, float(v))
            k = min(e, (j - i) // 2)
            if k:
                seg[:k] *= np.linspace(0, 1, k)
                seg[-k:] *= np.linspace(1, 0, k)
            g[i:j] = np.maximum(g[i:j], seg)
        return g

    # Bass: in at OPEN, gone for the stop AND the honest stretch, back at
    # REBUILD, gone again for the fly, full at WARM.
    bas *= gate((OPEN, STOP, 1.0), (REBUILD, FLY, 1.0), (WARM, TAIL, 1.0))
    # Drums: in at DRUMS, dead at STOP, half-weight through the honest stretch.
    drm *= gate((DRUMS, STOP, 1.0), (RETURN, REBUILD, 0.42),
                (REBUILD, FLY, 0.85), (WARM, TAIL, 1.0))
    pads *= gate((OPEN, STOP, 0.9), (REBUILD, FLY, 0.7), (WARM, LEN, 1.0))
    # The ostinato itself drops out only for the stop.
    ost *= gate((0, STOP, 1.0), (RETURN, LEN, 1.0))

    dry = ost * 0.42 + bas * 0.50 + pads * 0.30 + drm * 0.38
    # One long tail over the stop: the reverb is fed the bar BEFORE it, so what
    # rings out at 0:28 is the music that just died, not a new sound.
    wet = reverb(dry, decay=2.8, mix=0.26)

    # Fade in from nothing, tail out under the URL.
    wet *= ramp(0, T0 + BAR, 0.0, 1.0) * ramp(TAIL, LEN, 1.0, 0.0)

    # DC blocker. The saw pad and the FFT filters both leave an offset, and an
    # offset is headroom spent on nothing plus a click at the fade edges.
    wet = wet - np.convolve(wet, np.ones(2048) / 2048, mode="same")
    peak = np.max(np.abs(wet))
    wet /= peak / 0.89
    # A touch of width: the pad and the hats off-centre, everything else middle.
    left  = wet + 0.05 * np.roll(pads, 300) * 0.30
    right = wet - 0.05 * np.roll(pads, -300) * 0.30
    st = np.stack([left, right], axis=1)
    st /= max(np.max(np.abs(st)) / 0.95, 1.0)
    return st

def write_wav(path, data):
    import wave, struct
    d = (np.clip(data, -1, 1) * 32767).astype("<i2")
    with wave.open(path, "wb") as w:
        w.setnchannels(2); w.setsampwidth(2); w.setframerate(SR)
        w.writeframes(d.tobytes())

if __name__ == "__main__":
    out = sys.argv[1] if len(sys.argv) > 1 else "docs/trailer/assets/score.wav"
    os.makedirs(os.path.dirname(out) or ".", exist_ok=True)
    write_wav(out, mix())
    print("%s  %.1f s  %.1f MB" % (out, LEN, os.path.getsize(out) / 1e6))
