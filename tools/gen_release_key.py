#!/usr/bin/env python3
"""Generate (or rotate) the offline release-signing key, and bake its public
half into the client.

    tools/gen_release_key.py --out-private <path-to-keep-SECRET>

WHY THIS EXISTS

The in-game updater checks a SHA-256 for every download, but that digest arrives
over the same connection as the file (GitHub). It catches a corrupted download,
not a compromised release host: whoever can swap the asset can swap the digest.
See SECURITY.md.

The fix is a signature the release host never holds. An Ed25519 PRIVATE key lives
offline -- on a maintainer's machine or in a CI secret -- and signs a small
manifest (version + each asset's SHA-256) at release time (tools/sign_release.py).
The matching PUBLIC key is compiled into the client (src/ReleaseSigningKey.h). A
tampered release fails the signature, which no amount of control over GitHub can
forge. The client only ever VERIFIES (src/util/Ed25519.h has no signing path),
so the secret never touches the game.

WHAT THIS DOES

  * Generates an Ed25519 keypair with openssl (PureEdDSA, RFC 8032 -- the same
    scheme ed25519Verify checks, proven to interoperate by
    tests/release_signing_test).
  * Writes the PRIVATE key where you tell it, and nowhere else. Treat that file
    as a credential: store it as the CI secret RELEASE_SIGNING_KEY (the whole PEM)
    and delete the local copy, or keep it offline. It is NEVER committed.
  * Rewrites the two committed PUBLIC artifacts: src/ReleaseSigningKey.h (the
    32-byte key the client compiles in) and sdk/release_signing_key.pub (its hex,
    for reference and for sign_release.py to sanity-check against).

ROTATION. Run it again with a fresh --out-private to replace the key. Commit the
regenerated public artifacts, update the CI secret, and the next release signs
with the new key while clients built from the new public key verify it. A client
built against the OLD public key will not verify a release signed by the NEW key,
so rotate in a release that itself ships the new public key.
"""

import argparse
import os
import subprocess
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
HEADER = os.path.join(ROOT, "src", "ReleaseSigningKey.h")
PUBHEX = os.path.join(ROOT, "sdk", "release_signing_key.pub")


def run(cmd, **kw):
    return subprocess.run(cmd, check=True, capture_output=True, **kw)


def raw_public_key(priv_pem: str) -> bytes:
    """The 32-byte Ed25519 public key: the tail of the DER SubjectPublicKeyInfo,
    whose Ed25519 prefix is a fixed 12 bytes."""
    der = run(["openssl", "pkey", "-in", priv_pem, "-pubout", "-outform", "DER"]).stdout
    if len(der) < 32:
        raise SystemExit("openssl did not return a usable public key")
    return der[-32:]


def write_header(pub: bytes):
    rows = []
    for i in range(0, 32, 8):
        rows.append("    " + " ".join(f"0x{b:02x}," for b in pub[i:i + 8]))
    body = "\n".join(rows)
    with open(HEADER, "w", encoding="utf-8") as f:
        f.write(
            "#pragma once\n\n"
            "// The release-signing PUBLIC key, 32 bytes, Ed25519.\n"
            "//\n"
            "// GENERATED by tools/gen_release_key.py -- do not edit by hand. The\n"
            "// matching private key is offline (a CI secret, never in the tree); it\n"
            "// signs the release manifest that GameUpdates verifies against this key,\n"
            "// so a tampered release on the host fails the check. See SECURITY.md and\n"
            "// tools/sign_release.py.\n"
            "//\n"
            "// All-zero means NO key is pinned yet: the updater then falls back to\n"
            "// opening the release page rather than self-installing an unverifiable\n"
            "// download. Run tools/gen_release_key.py to pin one.\n\n"
            "#include <cstdint>\n\n"
            "inline constexpr uint8_t kReleaseSigningPublicKey[32] = {\n"
            f"{body}\n"
            "};\n")


def write_pubhex(pub: bytes):
    os.makedirs(os.path.dirname(PUBHEX), exist_ok=True)
    with open(PUBHEX, "w", encoding="utf-8") as f:
        f.write(pub.hex() + "\n")


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--out-private", required=True,
                    help="where to write the SECRET private key PEM (kept out of "
                         "the repo; store as CI secret RELEASE_SIGNING_KEY)")
    ap.add_argument("--force", action="store_true",
                    help="overwrite an existing private-key file")
    args = ap.parse_args()

    if os.path.exists(args.out_private) and not args.force:
        raise SystemExit(f"{args.out_private} exists; pass --force to overwrite")

    inside = os.path.abspath(args.out_private).startswith(ROOT + os.sep)
    if inside:
        print("WARNING: the private key path is inside the repository. Make sure "
              "it is gitignored and never committed.", file=sys.stderr)

    run(["openssl", "genpkey", "-algorithm", "ed25519", "-out", args.out_private])
    os.chmod(args.out_private, 0o600)
    pub = raw_public_key(args.out_private)
    write_header(pub)
    write_pubhex(pub)

    print(f"private key : {args.out_private}  (SECRET -- do not commit)")
    print(f"public key  : {pub.hex()}")
    print(f"baked into  : {os.path.relpath(HEADER, ROOT)}")
    print(f"              {os.path.relpath(PUBHEX, ROOT)}")
    print()
    print("Next: store the private key as the CI secret RELEASE_SIGNING_KEY (the")
    print("whole PEM), delete the local copy if you do not need it, commit the two")
    print("public artifacts, and releases from now on will be signed and verified.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
