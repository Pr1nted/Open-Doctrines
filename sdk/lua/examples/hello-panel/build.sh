#!/usr/bin/env bash
# Builds hello-panel-lua.odmod: Lua 5.4.7 plus main.lua, as one wasm module.
#
# Needs emcc. Unlike the other SDKs this one cannot use a bare
# `clang --target=wasm32 -nostdlib`: Lua wants a libc (malloc, snprintf, strtod,
# the math functions), and emcc's standalone-wasm sysroot is the one that
# provides it while importing nothing but wasi_snapshot_preview1.
set -eu
here="$(cd "$(dirname "$0")" && pwd)"
root="$(cd "$here/../../../.." && pwd)"
sdk="$root/sdk"
luadir="$sdk/lua"

LUA_VER=5.4.7
src="$luadir/.lua-src/lua-$LUA_VER/src"

command -v emcc >/dev/null 2>&1 || {
    echo "emcc not found. Install Emscripten: https://emscripten.org/docs/getting_started/downloads.html" >&2
    exit 1
}

# --- Lua source, fetched once and cached -------------------------------------
if [ ! -d "$src" ]; then
    echo "fetching lua-$LUA_VER..."
    mkdir -p "$luadir/.lua-src"
    curl -fsSL "https://www.lua.org/ftp/lua-$LUA_VER.tar.gz" \
        | tar xz -C "$luadir/.lua-src"
fi

# --- main.lua -> script.h ----------------------------------------------------
# There is no filesystem in the sandbox, so the script travels as bytes in the
# module's data section.
python3 - "$here/main.lua" "$here/script.h" <<'PY'
import sys, pathlib
src, dst = pathlib.Path(sys.argv[1]), pathlib.Path(sys.argv[2])
data = src.read_bytes()
rows = [", ".join(f"0x{b:02x}" for b in data[i:i+16]) for i in range(0, len(data), 16)]
body = ",\n    ".join(rows)
dst.write_text(
    "/* Generated by build.sh from %s. Do not edit. */\n"
    "#ifndef GBX_SCRIPT_H\n#define GBX_SCRIPT_H\n\n"
    "static const unsigned char gbx_script[] = {\n    %s\n};\n"
    "static const unsigned int gbx_script_len = %d;\n"
    "static const char gbx_script_name[] = \"@%s\";\n\n"
    "#endif\n" % (src.name, body, len(data), src.name)
)
print(f"  embedded {src.name} ({len(data)} bytes)")
PY

# --- Lua core ----------------------------------------------------------------
# Everything except: linit.c (we register our own library set), liolib.c,
# loslib.c, loadlib.c and ldblib.c. Those four are the ones that reach for a
# filesystem, a clock or a shell, and leaving them uncompiled is what keeps the
# module's WASI surface down to fd_write. See gearbox_lua.c: gbx_open_libs.
core="lapi lcode lctype ldebug ldo ldump lfunc lgc llex lmem lobject lopcodes
      lparser lstate lstring ltable ltm lundump lvm lzio
      lbaselib lcorolib lmathlib lstrlib ltablib lutf8lib"

srcs=""
for f in $core; do srcs="$srcs $src/$f.c"; done

# lauxlib.c is compiled on its own so the loadfilex rename below applies to it
# and not to gearbox_lua.c, which supplies the replacement.
obj="$luadir/.lua-src/lauxlib.o"
emcc -O2 -c -DNDEBUG \
     -DluaL_loadfilex=gbx_lua_unused_loadfilex \
     -ffunction-sections -fdata-sections \
     -I "$sdk" -I "$luadir" -I "$src" \
     -include "$luadir/gbx_throw.h" \
     -o "$obj" "$src/lauxlib.c"

# Two flags below are load-bearing rather than tuning:
#
#   -DluaL_loadfilex=...  renames Lua's file loader so gearbox_lua.c can supply
#                         its own. Lua's calls freopen, which pulls in stdio,
#                         which imports env.__syscall_dup3 -- outside the ABI,
#                         so the host refuses the mod. With the rename plus
#                         --gc-sections the original is unreferenced and dropped.
#
#   no ALLOW_MEMORY_GROWTH  it imports env.emscripten_notify_memory_growth,
#                           also outside the ABI. A mod gets a fixed heap.
#
# -include gbx_throw.h must come before Lua's own ldo.c definitions; see that
# file for why setjmp/longjmp is off the table here.
emcc -O2 -sSTANDALONE_WASM --no-entry \
     -sSUPPORT_LONGJMP=0 \
     -sERROR_ON_UNDEFINED_SYMBOLS=0 \
     -sMALLOC=emmalloc \
     -sINITIAL_MEMORY=8MB \
     -sSTACK_SIZE=256KB \
     -sASSERTIONS=0 \
     -DNDEBUG \
     -ffunction-sections -fdata-sections -Wl,--gc-sections \
     -I "$sdk" -I "$luadir" -I "$src" -I "$here" \
     -include "$luadir/gbx_throw.h" \
     -o "$here/mod.wasm" \
     $srcs "$obj" "$luadir/gearbox_lua.c"

python3 "$root/tools/wasm_imports.py" "$here/mod.wasm"
"$root/tools/pack_odmod.sh" "$here" "$here/hello-panel-lua.odmod"

ls -l "$here/mod.wasm" "$here/hello-panel-lua.odmod" | awk '{printf "  %-12s %8d bytes\n", $NF, $5}'
